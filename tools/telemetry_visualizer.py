#!/usr/bin/env python3
"""
tools/telemetry_visualizer.py

Standalone post-mortem telemetry analyzer and trajectory smoothness evaluator.
Parses CSV flight data logs generated by Beacon's TelemetryRecorder, computing
kinodynamic tracking accuracy, jerk integral metrics, and energy efficiency.
"""

import sys
import os
import csv
import math
from typing import List, Dict, Any

def parse_telemetry_csv(csv_path: str) -> List[Dict[str, Any]]:
    if not os.path.exists(csv_path):
        print(f"Error: Telemetry file not found: {csv_path}", file=sys.stderr)
        return []
        
    records = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                records.append({
                    "sim_time": float(row["sim_time"]),
                    "agent_id": row["agent_id"],
                    "pos_x": float(row["pos_x"]),
                    "pos_y": float(row["pos_y"]),
                    "pos_z": float(row["pos_z"]),
                    "speed_mps": float(row["speed_mps"]),
                    "heading_rad": float(row["heading_rad"]),
                    "battery_soc": float(row["battery_soc"]),
                    "rmse": float(row["rmse"])
                })
            except (ValueError, KeyError):
                continue
    return records

def compute_kinodynamic_metrics(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    if not records:
        return {"error": "No records to evaluate"}
        
    # Group by agent
    agents: Dict[str, List[Dict[str, Any]]] = {}
    for r in records:
        agents.setdefault(r["agent_id"], []).append(r)
        
    fleet_metrics = {}
    total_distance_all = 0.0
    
    for agent_id, traj in agents.items():
        if len(traj) < 2:
            continue
            
        traj.sort(key=lambda x: x["sim_time"])
        
        speeds = [p["speed_mps"] for p in traj]
        max_speed = max(speeds)
        avg_speed = sum(speeds) / len(speeds)
        
        # Distance calculation
        dist = 0.0
        for i in range(len(traj) - 1):
            dx = traj[i+1]["pos_x"] - traj[i]["pos_x"]
            dz = traj[i+1]["pos_z"] - traj[i]["pos_z"]
            dist += math.sqrt(dx*dx + dz*dz)
            
        total_distance_all += dist
        
        # Jerk estimation
        jerks = []
        for i in range(len(traj) - 2):
            dt1 = max(1e-4, traj[i+1]["sim_time"] - traj[i]["sim_time"])
            dt2 = max(1e-4, traj[i+2]["sim_time"] - traj[i+1]["sim_time"])
            a1 = (traj[i+1]["speed_mps"] - traj[i]["speed_mps"]) / dt1
            a2 = (traj[i+2]["speed_mps"] - traj[i+1]["speed_mps"]) / dt2
            jerk = (a2 - a1) / (0.5 * (dt1 + dt2))
            jerks.append(jerk)
            
        avg_jerk = (sum(abs(j) for j in jerks) / len(jerks)) if jerks else 0.0
        max_jerk = max(abs(j) for j in jerks) if jerks else 0.0
        
        final_soc = traj[-1]["battery_soc"]
        initial_soc = traj[0]["battery_soc"]
        soc_consumed = max(0.0, initial_soc - final_soc)
        
        fleet_metrics[agent_id] = {
            "total_samples": len(traj),
            "distance_m": dist,
            "avg_speed_mps": avg_speed,
            "max_speed_mps": max_speed,
            "avg_jerk_mps3": avg_jerk,
            "max_jerk_mps3": max_jerk,
            "battery_consumed_pct": soc_consumed * 100.0,
            "final_tracking_rmse_m": traj[-1]["rmse"]
        }
        
    return {
        "agent_count": len(agents),
        "total_distance_m": total_distance_all,
        "agents": fleet_metrics
    }

def print_summary_report(metrics: Dict[str, Any]) -> None:
    print("=" * 72)
    print("   BEACON TELEMETRY ANALYSIS REPORT")
    print("=" * 72)
    print(f"Total Active Agents Evaluated: {metrics.get('agent_count', 0)}")
    print(f"Total Fleet Trajectory Distance: {metrics.get('total_distance_m', 0.0):.2f} m")
    print("-" * 72)
    print(f"{'AGENT ID':<16} {'DIST (m)':<12} {'AVG SPEED':<12} {'MAX JERK':<12} {'BATTERY USE'}")
    print("-" * 72)
    
    for agent_id, data in metrics.get("agents", {}).items():
        print(f"{agent_id:<16} {data['distance_m']:<12.1f} {data['avg_speed_mps']:<12.2f} {data['max_jerk_mps3']:<12.2f} {data['battery_consumed_pct']:.2f}%")
    print("=" * 72)

def main():
    if len(sys.argv) < 2:
        print("Usage: python3 tools/telemetry_visualizer.py <path_to_telemetry.csv>")
        sys.exit(0)
        
    csv_file = sys.argv[1]
    records = parse_telemetry_csv(csv_file)
    if not records:
        print("No valid telemetry records found.")
        sys.exit(1)
        
    metrics = compute_kinodynamic_metrics(records)
    print_summary_report(metrics)

if __name__ == "__main__":
    main()
